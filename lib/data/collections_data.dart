// Helper function to get products by collection ID
List<Product> getProductsByCollection(String collectionId) {
  if (collectionId == 'bestsellers') {
    // Best Sellers includes specific popular products from other collections
    return allProducts.where((p) => 
      p.id == 'p1' || // Classic Hoodie
      p.id == 'p2' || // Union T-Shirt
      p.id == 'p6' || // Classic Beanie Hat
      p.id == 'p7' || // Lanyard
      p.id == 'p10' || // A5 Notebook
      p.id == 'p11' // Ballpoint Pen
    ).toList();
  }
  return allProducts.where((p) => p.collectionId == collectionId).toList();
}

// Helper function to get sale products
List<Product> getSaleProducts() {
  return allProducts.where((p) => p.isOnSale).toList();
}

// Helper function to get products in stock
List<Product> getInStockProducts() {
  return allProducts.where((p) => p.inStock).toList();
}

// Helper function to search products by name or description
List<Product> searchProducts(String query) {
  final lowerQuery = query.toLowerCase();
  return allProducts.where((p) => 
    p.name.toLowerCase().contains(lowerQuery) ||
    p.description.toLowerCase().contains(lowerQuery) ||
    p.category.toLowerCase().contains(lowerQuery)
  ).toList();
}

